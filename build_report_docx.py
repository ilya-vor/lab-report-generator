# ---------------------------------------------------------------------------
# 4. Правим header1.xml (тема в штампе) и settings.xml (автообновление TOC)
# ---------------------------------------------------------------------------
def patch_package():
    tmp = OUT + ".tmp"
    zin = zipfile.ZipFile(OUT)
    zout = zipfile.ZipFile(tmp, "w", zipfile.ZIP_DEFLATED)
    for item in zin.infolist():
        data = zin.read(item.filename)
        if item.filename == "word/header1.xml":
            s = data.decode("utf-8")
            s = s.replace(OLD_HEADER_TITLE, SHORT_TITLE)
            s = s.replace(OLD_TEACHER, TEACHER)
            s = patch_group_runs(s, OLD_GROUP, GROUP)
            data = s.encode("utf-8")
        elif item.filename == "word/settings.xml":
            s = data.decode("utf-8")
            if "<w:updateFields" not in s:
                ins = '<w:updateFields w:val="true"/>'
                idx = s.find("<w:hdrShapeDefaults")
                if idx >= 0:
                    s = s[:idx] + ins + s[idx:]
                else:
                    s = s.replace("</w:settings>", ins + "</w:settings>", 1)
            data = s.encode("utf-8")
        zout.writestr(item, data)
    zout.close()
    zin.close()
    os.replace(tmp, OUT)


# ---------------------------------------------------------------------------
# 5. Сборка
# ---------------------------------------------------------------------------
def build():
    doc = Document(TEMPLATE)
    clear_content(doc)      # сначала убираем старое наполнение
    patch_title_page(doc)   # затем правим/сжимаем титульный лист
    build_content(doc)      # и добавляем новое наполнение
    doc.save(OUT)
    patch_package()
    print("Saved:", OUT)


if __name__ == "__main__":
    build()
