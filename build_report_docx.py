def set_wt_text(elem, old, new):
    """Заменяет текст во всех w:t элемента внутри elem."""
    if old == new:
        return 0
    n = 0
    for t in elem.iter(qn("w:t")):
        if t.text and old in t.text:
            t.text = t.text.replace(old, new)
            n += 1
    return n


def replace_whole_text(elem, new):
    """Заменяет текст абзаца целиком (формат первого run сохраняется)."""
    ts = list(elem.iter(qn("w:t")))
    if not ts:
        return
    ts[0].text = new
    ts[0].set("{http://www.w3.org/XML/1998/namespace}space", "preserve")
    for t in ts[1:]:
        t.text = ""


def replace_cell_text(tbl, old, new):
    """Заменяет текст в ячейках таблицы (в т.ч. разбитый на runs)."""
    for p in tbl.iter(qn("w:p")):
        txt = "".join(t.text or "" for t in p.iter(qn("w:t")))
        if old in txt:
            replace_whole_text(p, txt.replace(old, new))


# В header1 группа записана тремя runs: «МО-» + «4» + «26Б»
_GROUP_RE = re.compile(
    r"(<w:t[^>]*>)МО-</w:t>(.*?)(<w:t[^>]*>)4</w:t>(.*?)(<w:t[^>]*>)26Б</w:t>",
    re.S,
)


def patch_group_runs(xml, old, new):
    """Меняет группу в штампе header1 (текст разбит на несколько runs)."""
    if old != "МО-426Б":
        return xml
    return _GROUP_RE.sub(
        lambda m: "%s%s</w:t>%s%s</w:t>%s%s</w:t>" % (
            m.group(1), new, m.group(2), m.group(3), m.group(4), m.group(5)),
        xml)


# Ширины колонок штампа на титуле. Чтобы более длинная группа (КАИД-104М)
# помещалась в одну строку, колонка «Группа» расширена, а «Фамилия И.О.» сужена.
_STAMP_W = {1534: 2169, 273: 283, 2603: 1958, 2757: 3402}


def fix_stamp_widths(tbl):
    """Корректирует ширины колонок штампа (tblGrid + ячейки)."""
    grid = tbl.find(qn("w:tblGrid"))
    if grid is not None:
        for gc in grid.findall(qn("w:gridCol")):
            try:
                w = int(gc.get(qn("w:w")))
            except (TypeError, ValueError):
                continue
            if w in _STAMP_W:
                gc.set(qn("w:w"), str(_STAMP_W[w]))
    for tw in tbl.iter(qn("w:tcW")):
        try:
            w = int(tw.get(qn("w:w")))
        except (TypeError, ValueError):
            continue
        if w in _STAMP_W:
            tw.set(qn("w:w"), str(_STAMP_W[w]))


def title_par(doc, text, size, bold=False):
    p = doc.add_paragraph()
    p.alignment = WD_ALIGN_PARAGRAPH.CENTER
    r = p.add_run(text)
    r.font.name = "Times New Roman"
    r.font.size = Pt(size)
    r.bold = bold
    return p


def body_p(doc, text):
    p = doc.add_paragraph(style="Основной_ЛР")
    p.add_run(text)
    return p


def set_cell(cell, text, size=12, bold=False, align=None):
    cell.text = ""
    p = cell.paragraphs[0]
    if align is not None:
        p.alignment = align
    r = p.add_run(text)
    r.font.name = "Times New Roman"
    r.font.size = Pt(size)
    r.bold = bold


def add_table(doc, headers, rows, widths, size=11, caption=None):
    if caption:
        cp = doc.add_paragraph()
        cr = cp.add_run(caption)
        cr.font.name = "Times New Roman"
        cr.font.size = Pt(12)
    t = doc.add_table(rows=1, cols=len(headers))
    t.style = "Table Grid"
    t.alignment = WD_TABLE_ALIGNMENT.CENTER
    for i, h in enumerate(headers):
        set_cell(t.rows[0].cells[i], h, size=size, bold=True,
                 align=WD_ALIGN_PARAGRAPH.CENTER)
    for row in rows:
        cells = t.add_row().cells
        for i, val in enumerate(row):
            set_cell(cells[i], val, size=size)
    for row in t.rows:
        for i, w in enumerate(widths):
            row.cells[i].width = Cm(w)
    return t


