def patch_title_page(doc):
    kids = list(doc.element.body)
    replace_whole_text(kids[1], DEPT)                     # институт / кафедра
    set_wt_text(kids[6], OLD_PAGE_TITLE, FULL_TITLE)      # тема
    set_wt_text(kids[11], OLD_DISCIPLINE, DISCIPLINE)     # дисциплина
    # группа в штампе (в шаблоне текст разбит на runs «МО-» + «4» + «26Б»)
    replace_cell_text(kids[16], OLD_GROUP, GROUP)
    # расширяем колонку, чтобы «КАИД-104М» влезало в одну строку
    fix_stamp_widths(kids[16])
    # преподаватель в штампе: строки «Консультант» и «Принял»
    # (перед фамилией в шаблоне стоит пробел - сохраняем его)
    rows = kids[16].findall(qn("w:tr"))
    for ri in (4, 5):
        tc = rows[ri].findall(qn("w:tc"))
        if len(tc) > 1:
            replace_whole_text(tc[1], " " + TEACHER)
    # Убираем лишние пустые абзацы, чтобы титул уверенно
    # помещался на одной странице при длинной дисциплине
    for idx in (20, 19, 18):
        body = doc.element.body
        body.remove(kids[idx])


