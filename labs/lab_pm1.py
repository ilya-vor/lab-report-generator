def num(value):
    """Целое с разделением разрядов неразрывным пробелом."""
    return format(int(round(value)), ",").replace(",", "\u00a0")


def _ru(value, spec):
    """Число в русской записи: пробел между разрядами, запятая в дробной."""
    return format(value, spec).replace(",", " ").replace(".", ",")


def f1(value):
    return _ru(value, ",.1f")


def f2(value):
    return _ru(value, ",.2f")


def size_label(n):
    if n >= 1_000_000:
        return "1 млн"
    return "%d тыс." % (n // 1000)


