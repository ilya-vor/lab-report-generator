# Рисунок 3. Декомпозиция A0: пять функций с дугами IDEF0
# ---------------------------------------------------------------------------
IMG_IDEF0_DECOMP = os.path.join(OUT_DIR, "lab5_idef0_a0.png")


def scheme_idef0_decomp(show=False):
    """Декомпозиция A0 на блоки A1-A5 в нотации IDEF0 (лестница).

    Блоки идут каскадом вниз-вправо, поэтому у каждого открыты левая грань
    (вход), верх (управление) и низ (механизм). Смещение по x больше ширины
    блока: в коридоре между блоками проходит стрелка от выхода предыдущего
    блока к входу следующего, а подписи дуг лежат в свободных полосах между
    рядами.
    """
    wide, high = 560.0, 500.0
    bw, bh = 76.0, 56.0
    xs = [108.0 + 88.0 * i for i in range(5)]
    ys = [412.0 - 88.0 * i for i in range(5)]
    blocks = [
        ("a1", "A1", "Планировать\nконтроль\nсмены"),
        ("a2", "A2", "Принимать и\nготовить\nвидеопоток"),
        ("a3", "A3", "Распознавать\nСИЗ"),
        ("a4", "A4", "Фиксировать и\nуведомлять"),
        ("a5", "A5", "Анализировать\nи отчитываться"),
    ]
    boxes = [Box(bid, text, xs[i], ys[i], bw, bh, title=num, fs=7.0)
             for i, (bid, num, text) in enumerate(blocks)]

    def mark(mid, x, y):
        boxes.append(Box(mid, "", x, y, 0.2, 0.2, kind="text"))
        return mid

    links = []
    # цепочка: выход блока i - вход блока i+1. Стрелка идёт строго по
    # ортогональной ломаной: вправо в коридор между столбцами, вниз до
    # уровня входной грани и влево в блок, поэтому наконечник направлен
    # по горизонтали, а не по диагонали.
    chain = ["сменное задание", "кадры", "детекции СИЗ", "событие"]
    for i, text in enumerate(chain):
        corridor = xs[i] + bw / 2 + 4
        links.append(Link(blocks[i][0], blocks[i + 1][0], text,
                          s_side="r", t_side="l",
                          via=((corridor, ys[i]), (corridor, ys[i + 1])),
                          fs=6.2, label_at=0.5, label_ha="left",
                          label_dx=5, label_dy=0, label_va="center"))

    # внешние входы: слева, в нижнюю половину левой грани
    for mid, i, text in [("in1", 0, "сменное задание,\nдопуски"),
                         ("in2", 1, "видеопоток,\nчетыре камеры")]:
        mark(mid, 8.0, ys[i] - 16)
        links.append(Link(mid, blocks[i][0], text, t_side="l", t_off=-16,
                          fs=6.2, label_at=0.86, label_ha="right",
                          label_dx=-6, label_dy=5))

    # управление: сверху, в правую половину верхней грани
    for mid, i, text in [("c1", 0, "ГОСТ 12.4.011,\nрегламент охраны труда"),
                         ("c3", 2, "пороги детекции,\nправила зон"),
                         ("c4", 3, "время реакции,\nэскалация"),
                         ("c5", 4, "форма отчёта,\nпериод")]:
        mark(mid, xs[i] + 20, ys[i] + 58)
        links.append(Link(mid, blocks[i][0], text, t_side="t", t_off=20,
                          fs=6.2, label_at=0.5, label_ha="left",
                          label_dx=5, label_dy=0, label_va="center"))

    # механизмы: снизу, в левую половину нижней грани
    for mid, i, text in [("m1", 0, "мастер участка"),
                         ("m3", 2, "модуль распознавания\nYOLO11n"),
                         ("m4", 3, "сервис событий"),
                         ("m5", 4, "база данных\nPostgreSQL")]:
        mark(mid, xs[i] - 16, ys[i] - 58)
        links.append(Link(mid, blocks[i][0], text, t_side="b", t_off=-16,
                          fs=6.2, label_at=0.5, label_ha="right",
                          label_dx=-5, label_dy=0, label_va="center"))

    # внешние выходы: справа
    for mid, i, text in [("o4", 3, "уведомление мастеру,\nслужбе ОТ"),
                         ("o5", 4, "отчёт за смену,\nвыгрузка в АСУ ОТ")]:
        mark(mid, wide - 26.0, ys[i])
        links.append(Link(blocks[i][0], mid, text, s_side="r", fs=6.2,
                          label_at=0.5, label_ha="center",
                          label_dy=5))

    path_png, path_svg = render(boxes, links, IMG_IDEF0_DECOMP,
                                height=high, width=wide)
    if show and hasattr(os, "startfile"):
        os.startfile(path_png)
    return path_png, path_svg


