# Рисунок 2. Дерево функций: декомпозиция A0 на A1-A5
# ---------------------------------------------------------------------------
def scheme_tree(show=False):
    """Декомпозиция контекста: пять функций, связанных с A0 шиной.

    Шина (горизонтальная линия) позволяет одному блоку A0 раскрыться в пять
    потомков без наклонных линий: вертикали потомков не пересекаются.
    """
    xs = [49, 145, 241, 337, 433]
    kids = [
        ("a1", "A1", "Планировать\nконтроль\nсмены"),
        ("a2", "A2", "Принимать и\nготовить\nвидеопоток"),
        ("a3", "A3", "Распознавать\nСИЗ"),
        ("a4", "A4", "Фиксировать и\nуведомлять"),
        ("a5", "A5", "Анализировать\nи отчитываться"),
    ]
    boxes = [Box("a0", "Контролировать применение СИЗ", 241, 168, 176, 46,
                 fs=8.2, bold=True, fill="#e8eef6")]
    links = []
    for (bid, num, text), x in zip(kids, xs):
        boxes.append(Box(bid, text, x, 62, 86, 74, title=num, fs=7.4))
        links.append(Link("a0", bid, "", arrow=False, s_side="b",
                          t_side="t", via=((241, 137), (x, 137))))
    path_png, path_svg = render(boxes, links, IMG_TREE, height=216)
    if show and hasattr(os, "startfile"):
        os.startfile(path_png)
    return path_png, path_svg


