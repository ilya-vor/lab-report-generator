def _series(data):
    rows = data["rows"]
    xs = [r["n"] for r in rows]
    get = lambda key: [r["methods"][key]["median_ms"] for r in rows]  # noqa
    return rows, xs, (get("sequential"), get("matvec"), get("dot"),
                      get("both"))


