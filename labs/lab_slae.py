# Форматирование чисел в русской записи
# ---------------------------------------------------------------------------
def num(value):
    """Целое с разделением разрядов неразрывным пробелом."""
    return format(int(round(value)), ",").replace(",", "\u00a0")


def _ru(value, spec):
    return format(value, spec).replace(",", " ").replace(".", ",")


def f1(value):
    return _ru(value, ",.1f")


def f2(value):
    return _ru(value, ",.2f")


def tm(ms):
    """Время: до секунды в миллисекундах, дальше - в секундах."""
    return "%s с" % f2(ms / 1000.0) if ms >= 1000 else "%s мс" % f1(ms)


def pct(value):
    """Целое число процентов с правильным падежом слова «процент»."""
    n = int(round(value))
    if n % 100 in (11, 12, 13, 14):
        word = "процентов"
    elif n % 10 == 1:
        word = "процент"
    elif n % 10 in (2, 3, 4):
        word = "процента"
    else:
        word = "процентов"
    return "%d %s" % (n, word)


def sci(value):
    """Число в экспоненциальной записи с русской запятой: 8,6·10^-9."""
    mant, exp = ("%.1e" % value).split("e")
    return "%s·10^%s" % (_ru(float(mant), ",.1f"), int(exp))


