def scheme_taxonomy(show=False):
    """Таксономия: группировочные классы и их потомки.

    Потомки стоят в колонке под своим группировочным классом и
    выровнены по нижнему краю, поэтому колонки с разным числом классов
    заканчиваются на одной линии. Связи идут через вертикальный
    ствол слева от колонки: линии не проходят под блоками и
    треугольники обобщения не сливаются.
    """
    groups = [
        ("g_actor", "Субъект\n(Actor)",
         ["Сотрудник\n(Employee)", "Должность\n(Position)",
          "Компетенция\n(Competence)"]),
        ("g_struct", "Структура\n(Structure)",
         ["Предприятие\n(Enterprise)", "Подразделение\n(Division)",
          "Смена\n(Shift)"]),
        ("g_prod", "Производство\n(Production)",
         ["Продукция\n(Product)", "Операция\n(Operation)",
          "Процесс\n(MainProcess,\nSupportProcess)"]),
        ("g_res", "Ресурс\n(Resource)",
         ["Оборудование\n(Equipment)", "Материал\n(Material)",
          "СИЗ\n(PPE)"]),
        ("g_doc", "Документ\n(Document)",
         ["Регламент\n(Regulation)", "Сменное\nзадание",
          "Протокол\n(Protocol)"]),
        ("g_ctrl", "Контроль\n(Control)",
         ["Инцидент\n(Incident)", "Решение\n(Decision)",
          "Показатель\n(KPI)"]),
    ]
    x0, step, gw, cw = 42.0, 80.0, 72.0, 64.0
    rows = [113.0, 83.0, 53.0, 23.0]          # сверху вниз
    group_y, root_y = 150.0, 196.0

    boxes = [Box("thing", "owl:Thing", 242, root_y, 96, 22, fs=6.4,
                 bold=True, fill="#f2f2f2")]
    links = []
    for i, (gid, gtext, children) in enumerate(groups):
        x = x0 + step * i
        spine = x - 40.0
        child_rows = rows[4 - len(children):]
        boxes.append(Box(gid, gtext, x, group_y, gw, 30, fs=6.0, bold=True,
                         fill="#e8eef6"))
        links.append(Link("thing", gid, "", head="triangle", s_side="b",
                          t_side="t", via=((x, 175.0),)))
        # ствол колонки: короткая отводка от группы вниз, затем вниз до
        # нижнего потомка
        top_y, bot_y = 129.0, child_rows[-1]
        boxes.append(Box(gid + "_top", "", spine, top_y, 0.2, 0.2,
                         kind="text"))
        boxes.append(Box(gid + "_bot", "", spine, bot_y, 0.2, 0.2,
                         kind="text"))
        links.append(Link(gid, gid + "_top", "", arrow=False, s_side="b",
                          t_side="t", via=((x, top_y),)))
        links.append(Link(gid + "_top", gid + "_bot", "", arrow=False,
                          s_side="t", t_side="b"))
        for j, child in enumerate(children):
            cid = "%s_%d" % (gid, j)
            cy = child_rows[j]
            boxes.append(Box(cid, child, x + 6.0, cy, cw, 24, fs=5.3))
            boxes.append(Box(cid + "_in", "", spine, cy, 0.2, 0.2,
                             kind="text"))
            links.append(Link(cid + "_in", cid, "", head="triangle",
                              s_side="r", t_side="l"))
    path_png, path_svg = render(boxes, links, IMG_TAXO, height=220)
    if show and hasattr(os, "startfile"):
        os.startfile(path_png)
    return path_png, path_svg


