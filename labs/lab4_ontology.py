def scheme_uml(show=False):
    """Онтология в нотации UML: классы, атрибуты, отношения.

    Раскладка по строке «полномочия - деятельность - результат»:
    верхний ряд - должность, компетенция, регламент; средний -
    подразделение, сотрудник, процесс; нижний - продукция, инцидент,
    ресурс. Отношения композиции и агрегации показаны ромбами со
    стороны целого.
    """
    classes = [
        UmlClass("comp", "Компетенция", code="Competence", x=66, y=343,
                 w=112,
                 attrs=("compId: integer", "name: string",
                        "validUntil: date", "level: integer")),
        UmlClass("pos", "Должность", code="Position", x=231, y=343,
                 w=120,
                 attrs=("posId: integer", "title: string",
                        "isManager: boolean", "grade: integer")),
        UmlClass("reg", "Регламент", code="Regulation", x=399, y=343,
                 w=118,
                 attrs=("regId: integer", "code: string",
                        "version: integer", "approvedAt: date")),
        UmlClass("emp", "Сотрудник", code="Employee", x=66, y=246,
                 w=112, fill="#e8eef6",
                 attrs=("empId: integer", "fullName: string",
                        "hiredAt: date", "status: {active, leave}")),
        UmlClass("div", "Подразделение", code="Division", x=231, y=246,
                 w=120, fill="#e8eef6",
                 attrs=("divId: integer", "name: string",
                        "kind: {shop, section, service}",
                        "manager: Employee")),
        UmlClass("proc", "Процесс", code="Process", x=399, y=246, w=118,
                 attrs=("procId: integer", "name: string",
                        "owner: Division")),
        UmlClass("inc", "Инцидент", code="Incident", x=66, y=150, w=112,
                 attrs=("incId: integer", "at: dateTime",
                        "kind: string", "confirmed: boolean")),
        UmlClass("res", "Ресурс", code="Resource", x=231, y=150, w=120,
                 fill="#eaf3ea",
                 attrs=("resId: integer", "name: string",
                        "kind: {equipment, material, ppe}", "cost: float")),
        UmlClass("prod", "Продукция", code="Product", x=399, y=150,
                 w=118,
                 attrs=("prodId: integer", "name: string",
                        "unit: string", "price: float")),
        UmlClass("dec", "Решение", code="Decision", x=66, y=53, w=112,
                 attrs=("decId: integer", "at: dateTime",
                        "action: string", "by: Employee")),
    ]
    links = [
        # верхний ряд: полномочия и требования
        Link("emp", "comp", "hasCompetence 0..*", s_side="t", t_side="b",
             label_dx=5, label_ha="left", label_dy=0, fs=6.0),
        Link("emp", "pos", "holdsPosition 1", label_dx=6,
             label_ha="left", label_dy=2, fs=6.0),
        Link("pos", "div", "hasPosition 1..*", head="diamond",
             s_side="b", s_off=22, t_side="t", t_off=22,
             label_dx=5, label_ha="left", label_dy=0, fs=6.0),
        Link("reg", "proc", "governs 1..*", s_side="b", t_side="t",
             label_dx=5, label_ha="left", label_dy=0, fs=6.0),
        # средний ряд: структура и деятельность
        Link("emp", "div", "worksIn 1", head="diamond", s_side="r",
             t_side="l", label_dy=8, fs=6.0),
        Link("div", "proc", "hasProcess\n1..*", s_side="r", t_side="l",
             label_dy=8, fs=5.8),
        # нижний ряд: результаты и ресурсы
        Link("emp", "inc", "caused 0..*", s_side="b", t_side="t",
             label_dx=5, label_ha="left", label_dy=0, fs=6.0),
        Link("inc", "res", "involvesResource\n0..*", s_side="r",
             t_side="l", label_dx=0, label_ha="center", label_dy=-11,
             fs=5.4),
        Link("res", "proc", "usesResource 1..*", head="diamond_open",
             s_side="t", s_off=30, t_side="b", t_off=-44,
             label_dx=5, label_ha="left", label_dy=-3, fs=6.0),
        Link("proc", "prod", "producesProduct\n0..*", s_side="b",
             t_side="t", label_dx=5, label_ha="left", label_dy=0, fs=5.8),
        Link("dec", "inc", "resolves 1", head="diamond", s_side="t",
             t_side="b", label_dx=5, label_ha="left", label_dy=0, fs=6.0),
    ]
    path_png, path_svg = render_classes(classes, links, IMG_UML, height=390)
    if show and hasattr(os, "startfile"):
        os.startfile(path_png)
    return path_png, path_svg


