def ru(value, digits=2):
    """Число с запятой в дробной части и пробелом между разрядами."""
    text = ("{:,.%df}" % digits).format(value)
    text = text.replace(",", "\u00a0").replace(".", ",")
    return text.replace("-", MINUS)


def pct(value, digits=2):
    return ru(value, digits) + " %"


def axis_pct(value, _pos=None):
    return ("%.0f" % value).replace("-", MINUS)


def best_of(values):
    return max(values, key=values.get)


def rank(values):
    order = sorted(values, key=values.get, reverse=True)
    return {t: order.index(t) + 1 for t in values}


def kendall_w(maps):
    """Коэффициент конкордации Кендалла для набора ранжирований."""
    n = len(TICKERS)
    m = len(maps)
    sums = {t: sum(place[t] for place in maps) for t in TICKERS}
    mean = sum(sums.values()) / float(n)
    spread = sum((value - mean) ** 2 for value in sums.values())
    return 12.0 * spread / (m * m * (n ** 3 - n))


def lead(values):
    return LABELS[best_of(values)]


